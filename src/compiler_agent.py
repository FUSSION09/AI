    # =========================================================================
    # 2. SANDBOXED COMPILATION & VERIFICATION
    # =========================================================================
    def sandbox_verify_patch(self, patch: ArchitecturalPatch) -> Tuple[bool, Dict[str, Any]]:
        """
        Validates the patch within a secure execution sandbox:
        1. Abstract Syntax Tree (AST) validation and forbidden call interception.
        2. Clean compilation to Python bytecode.
        3. Sandboxed execution and invocation of component's `self_test()`.
        4. Performance benchmark verification (< 2.0 ms execution latency).
        """
        verification_report = {
            "ast_syntax_valid": False,
            "security_whitelist_passed": False,
            "bytecode_compilation_passed": False,
            "functional_self_test_passed": False,
            "execution_latency_ms": 0.0,
            "verdict": "REJECTED"
        }

        # Step 1: AST Walk & Syntax Check
        try:
            tree = ast.parse(patch.code)
            verification_report["ast_syntax_valid"] = True
        except SyntaxError as e:
            verification_report["error"] = f"SyntaxError: {str(e)}"
            return False, verification_report

        # Security Check: Reject unauthorized system-level calls
        forbidden_calls = {"eval", "exec", "os.system", "subprocess", "socket", "ctypes"}
        for node in ast.walk(tree):
            if isinstance(node, ast.Name) and node.id in forbidden_calls:
                verification_report["error"] = f"Security Violation: Forbidden primitive '{node.id}'"
                return False, verification_report

        verification_report["security_whitelist_passed"] = True

        # Step 2: Bytecode Compilation
        try:
            compiled_code = compile(tree, filename=f"<{patch.patch_id}>", mode="exec")
            verification_report["bytecode_compilation_passed"] = True
        except Exception as e:
            verification_report["error"] = f"CompilationError: {str(e)}"
            return False, verification_report

        # Step 3: Sandboxed Execution & Functional Self-Test
        sandbox_scope = {}
        try:
            exec(compiled_code, sandbox_scope)

            # Find synthesized class
            synthesized_class = None
            for key, val in sandbox_scope.items():
                if isinstance(val, type) and hasattr(val, "self_test"):
                    synthesized_class = val
                    break

            if not synthesized_class:
                verification_report["error"] = "No valid component class exposing 'self_test()' found."
                return False, verification_report

            t0 = time.perf_counter()
            instance = synthesized_class()
            test_passed = instance.self_test()
            latency = (time.perf_counter() - t0) * 1000.0

            verification_report["functional_self_test_passed"] = bool(test_passed)
            verification_report["execution_latency_ms"] = round(latency, 3)

            if test_passed and latency < 50.0:
                verification_report["verdict"] = "VERIFIED_MISSION_READY"
                patch.status = "VERIFIED"
                patch.test_results = verification_report
                return True, verification_report
            else:
                verification_report["error"] = f"Self-test failed ({test_passed}) or latency exceeded ({latency:.2f}ms)."
                return False, verification_report

        except Exception as e:
            verification_report["error"] = f"ExecutionRuntimeError: {str(e)}"
            return False, verification_report

    # =========================================================================
    # 3. VERSIONING & COMMIT LEDGER (SHA-256 DAG)
    # =========================================================================
    def commit_evolution_patch(self, patch: ArchitecturalPatch) -> str:
        """
        Commits verified patch to disk and appends cryptographic record to Evolution Ledger.
        """
        parent_commit = self._get_latest_commit()
        patch.parent_commit = parent_commit

        # Compute SHA-256 Commit Hash
        hash_payload = f"{patch.patch_id}:{patch.target_subsystem}:{patch.code}:{parent_commit}:{patch.timestamp}"
        commit_hash = hashlib.sha256(hash_payload.encode("utf-8")).hexdigest()
        patch.commit_hash = commit_hash

        # 1. Save Python file into evolution/patches
        patch_file = PATCHES_DIR / f"{patch.patch_id}.py"
        with open(patch_file, "w", encoding="utf-8") as f:
            f.write(patch.code)

        # 2. Append to evolution_ledger.json
        with open(LEDGER_FILE, "r", encoding="utf-8") as f:
            ledger_data = json.load(f)

        commit_record = {
            "commit_hash": commit_hash,
            "parent_commit": parent_commit,
            "patch_id": patch.patch_id,
            "target_subsystem": patch.target_subsystem,
            "gap_addressed": patch.gap_addressed,
            "file_path": str(patch_file),
            "timestamp": patch.timestamp,
            "author": patch.author,
            "status": "COMMITTED"
        }

        ledger_data["commits"].append(commit_record)
        ledger_data["latest_commit"] = commit_hash
        ledger_data["total_evolutions"] = len(ledger_data["commits"])

        with open(LEDGER_FILE, "w", encoding="utf-8") as f:
            json.dump(ledger_data, f, indent=2)

        return commit_hash

    # =========================================================================
    # 4. HOT-RELOAD DEPLOYMENT & ZERO-DOWNTIME INJECTION
    # =========================================================================
    def deploy_hot_reload(self, patch: ArchitecturalPatch) -> Dict[str, Any]:
        """
        Dynamically loads and hot-swaps the synthesized component in the running Python process.
        """
        patch_file = PATCHES_DIR / f"{patch.patch_id}.py"
        if not patch_file.exists():
            return {"status": "FAILED", "error": f"Patch file {patch_file} does not exist."}

        # Dynamic Module Specification & Import
        spec = importlib.util.spec_from_file_location(patch.patch_id, str(patch_file))
        if not spec or not spec.loader:
            return {"status": "FAILED", "error": "Unable to build module spec."}

        module = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(module)

        # Instantiate component
        component_class = None
        for attr_name in dir(module):
            attr = getattr(module, attr_name)
            if isinstance(attr, type) and hasattr(attr, "self_test") and attr.__module__ == patch.patch_id:
                component_class = attr
                break

        if not component_class:
            return {"status": "FAILED", "error": "No verified component class found in loaded module."}

        instance = component_class()
        ActivePatchRegistry.register_patch(patch, instance)
        patch.status = "DEPLOYED"

        return {
            "status": "DEPLOYED_HOT_RELOAD",
            "patch_id": patch.patch_id,
            "target_subsystem": patch.target_subsystem,
            "commit_hash": patch.commit_hash,
            "component_class": component_class.__name__,
            "active_patches_count": len(ActivePatchRegistry._active_patches)
        }

    # =========================================================================
    # 5. ZERO-DOWNTIME ROLLBACK
    # =========================================================================
    def rollback_patch(self, patch_id: str) -> Dict[str, Any]:
        """Reverts a deployed patch back to baseline architecture."""
        success = ActivePatchRegistry.rollback(patch_id)
        if success:
            # Append rollback record to ledger
            with open(LEDGER_FILE, "r", encoding="utf-8") as f:
                ledger_data = json.load(f)

            ledger_data["commits"].append({
                "commit_hash": f"ROLLBACK-{patch_id[:12]}",
                "parent_commit": ledger_data.get("latest_commit", "ROOT"),
                "patch_id": patch_id,
                "action": "ROLLBACK_RESTORE_BASELINE",
                "timestamp": time.time(),
                "author": "COMPILER_AGENT_SIAA_V15"
            })
            with open(LEDGER_FILE, "w", encoding="utf-8") as f:
                json.dump(ledger_data, f, indent=2)

            return {"status": "ROLLED_BACK", "patch_id": patch_id, "restored_to_baseline": True}
        return {"status": "NOT_FOUND", "patch_id": patch_id}

    # =========================================================================
    # 6. AUTONOMOUS EVOLUTION CYCLE (END-TO-END)
    # =========================================================================
    def execute_autonomous_evolution_cycle(
        self,
        target_subsystem: str = "RL",
        gap_description: Optional[str] = None
    ) -> Dict[str, Any]:
        """
        Executes the entire self-modification evolutionary cycle:
        1. Synthesize code for diagnosed gap
        2. Sandbox verify (AST & self-test)
        3. Cryptographic ledger commit
        4. Hot-reload dynamic deployment into memory
        """
        t0 = time.perf_counter()
        gap = gap_description or "Unmodeled multi-hop liquidity slippage and reward bounds"

        # 1. Synthesize
        patch = self.synthesize_code_for_gap(target_subsystem, gap)

        # 2. Verify
        verified, report = self.sandbox_verify_patch(patch)
        if not verified:
            return {
                "status": "REJECTED_IN_SANDBOX",
                "patch_id": patch.patch_id,
                "report": report
            }

        # 3. Commit
        commit_hash = self.commit_evolution_patch(patch)

        # 4. Deploy Hot-Reload
        deploy_res = self.deploy_hot_reload(patch)

        total_elapsed_ms = (time.perf_counter() - t0) * 1000.0

        return {
            "status": "EVOLUTION_DEPLOYED_SUCCESSFULLY",
            "patch_id": patch.patch_id,
            "target_subsystem": patch.target_subsystem,
            "gap_addressed": patch.gap_addressed,
            "commit_hash": commit_hash,
            "deployment": deploy_res,
            "verification_report": report,
            "evolution_time_ms": round(total_elapsed_ms, 2)
        }


