@dataclass
class ArchitecturalPatch:
    """Represents an immutable, versioned code modification generated by the Compiler Agent."""
    patch_id: str
    target_subsystem: str  # "RL", "QPMK", "SCM", "HCL"
    gap_addressed: str
    code: str
    commit_hash: str = ""
    parent_commit: str = "ROOT"
    author: str = "COMPILER_AGENT_SIAA_V15"
    timestamp: float = 0.0
    status: str = "SYNTHESIZED"  # SYNTHESIZED, VERIFIED, DEPLOYED, ROLLED_BACK
    metrics_delta: Dict[str, Any] = field(default_factory=dict)
    test_results: Dict[str, Any] = field(default_factory=dict)


class ActivePatchRegistry:
    """Live in-memory registry holding active hot-reloaded patches."""
    _active_patches: Dict[str, ArchitecturalPatch] = {}
    _live_components: Dict[str, Any] = {}

    @classmethod
    def register_patch(cls, patch: ArchitecturalPatch, component_instance: Any):
        cls._active_patches[patch.patch_id] = patch
        cls._live_components[patch.target_subsystem] = component_instance

    @classmethod
    def get_component(cls, target_subsystem: str) -> Optional[Any]:
        return cls._live_components.get(target_subsystem)

    @classmethod
    def rollback(cls, patch_id: str) -> bool:
        if patch_id in cls._active_patches:
            patch = cls._active_patches[patch_id]
            cls._live_components.pop(patch.target_subsystem, None)
            patch.status = "ROLLED_BACK"
            return True
        return False

    @classmethod
    def list_active(cls) -> List[Dict[str, Any]]:
        return [asdict(p) for p in cls._active_patches.values() if p.status == "DEPLOYED"]


